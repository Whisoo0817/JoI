def items():
    """mcq.evaluate 형식으로 변환. 절 튜플 = (type, mods, text)."""
    from candidates import make_candidates
    out = []
    for i, (cmd, segs, gold) in enumerate(CH):
        segs3 = [(t, [], x) for t, x in segs]
        assert sorted(s for s, _, _ in gold) == list(range(len(segs))), cmd
        dis = make_candidates(gold, segs3, k=5, seed=100 + i)
        out.append((cmd, gold, segs3, dis))
    return out

