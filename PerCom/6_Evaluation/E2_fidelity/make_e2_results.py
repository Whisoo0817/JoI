"""Build the E2 result tables from the reference recomputations.

~/temp/bin/python make_e2_results.py  ->  RESULTS.md

Reads runs/e2_run.ref-frozen.jsonl and runs/e2_run.ref-current.jsonl (rerun_reference.py). Explorer verdicts come
from the run; reference outcomes and witness replays come from the recomputation. Every pair stays in the
denominator, including refusals, timeouts and reference-unsupported pairs.
"""
import gzip
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = HERE / "runs"
KINDS = ["correct", "fault", "llm"]
ORDER = [
    "AGREE-EQUIV-ON-CHECKED", "AGREE-DIVERGE", "EXPLORER-DIVERGE-CONFIRMED-BY-REF-ON-WITNESS",
    "FALSE-EQUIV-CANDIDATE", "FALSE-DIVERGE-CANDIDATE",
    "DIVERGE-WITNESS-ir:ok joi:unsupported", "DIVERGE-WITNESS-ir:unsupported joi:unsupported",
    "EXPLORER-REFUSED", "EXPLORER-TIMEOUT", "EXPLORER-ERROR",
]


def load(label):
    path = RUNS / f"e2_run.ref-{label}.jsonl"
    if not path.exists():
        path = path.with_name(path.name + ".gz")
        if not path.exists():
            return None
    text = gzip.open(path, "rt").read() if path.suffix == ".gz" else path.read_text()
    return {r["pair_id"]: r for r in map(json.loads, text.splitlines())}


def table(rows, key, cols):
    head = "| " + " | ".join(["", *cols, "total"]) + " |\n|" + "---|" * (len(cols) + 2) + "\n"
    names = [n for n in ORDER if any(key(r) == n for r in rows)] + sorted({key(r) for r in rows} - set(ORDER))
    body = ""
    for n in names:
        c = [sum(1 for r in rows if key(r) == n and r["_col"] == col) for col in cols]
        body += f"| {n} | " + " | ".join(map(str, c)) + f" | {sum(c)} |\n"
    tot = [sum(1 for r in rows if r["_col"] == col) for col in cols]
    return head + body + "| total | " + " | ".join(map(str, tot)) + f" | {sum(tot)} |\n"


def section(label, rows):
    rs = list(rows.values())
    for r in rs:
        r["_col"] = r["kind"]
    out = f"### Reference `{label}`\n\nAgreement by pair kind:\n\n" + table(rs, lambda r: r["agreement"], KINDS)
    out += "\nReference outcome by pair kind:\n\n" + table(rs, lambda r: r["reference"]["outcome"], KINDS)
    faults = [r for r in rs if r["kind"] == "fault"]
    fams = sorted({r["family"] for r in faults})
    for r in faults:
        r["_col"] = r["family"]
    out += "\nFault pairs, agreement by fault family:\n\n" + table(faults, lambda r: r["agreement"], fams)
    return out


def main():
    fro, cur = load("frozen"), load("current")
    assert fro.keys() == cur.keys()
    for p in fro:
        assert fro[p]["explorer"].get("verdict") == cur[p]["explorer"].get("verdict")
    rs = list(cur.values())
    md = "# E2 results (generated by `make_e2_results.py`)\n\n"
    md += f"Pairs: {len(rs)}. Explorer verdicts from `runs/e2_run.jsonl`; reference side recomputed twice: " \
          "`frozen` = reference at `649cb9c`, `current` = reference after the None-comparison decision " \
          "(FREEZE_MANIFEST.md, harness corrections). Hand inspection: `INSPECTION_2026-09-14.md`.\n\n"
    for r in rs:
        r["_col"] = r["kind"]
    md += "## Explorer verdicts\n\n" + table(rs, lambda r: r["explorer"].get("verdict"), KINDS)
    walls = sorted(r["wall_seconds"] for r in rs)
    md += f"\nWall time per pair: median {walls[len(walls) // 2]:.0f} s, max {walls[-1]:.0f} s, " \
          f"total {sum(walls):.0f} s (Explorer budget 120 s of exploration per pair).\n\n"
    md += "## Agreement\n\n" + section("current", cur) + "\n" + section("frozen", fro)
    md += "\n## Frozen vs current\n\n| pair | reference outcome | agreement frozen | agreement current |\n|---|---|---|---|\n"
    n = 0
    for p in sorted(fro):
        f, c = fro[p], cur[p]
        if (f["reference"]["outcome"], f["agreement"]) != (c["reference"]["outcome"], c["agreement"]):
            n += 1
            md += f"| {p} | {f['reference']['outcome']} → {c['reference']['outcome']} | {f['agreement']} | {c['agreement']} |\n"
    md += f"\n{n} pairs differ; every difference is a witness replay that the frozen reference refused on a " \
          "None ordered comparison.\n" if n else "\nNo differences.\n"
    supp = load("current-supp")
    if supp:
        srs = list(supp.values())
        for r in srs:
            r["_col"] = r["kind"]
        ran = [r for r in srs if "reference_supplement" in r]
        md += "\n## Supplementary histories (PROTOCOL_DRAFT §9, added after the frozen run)\n\n"
        md += f"The current reference was rerun on `histories/supplement_histories.json` for the {len(ran)} pairs that " \
              "were REF-EQUIV-CHECKED on the frozen histories; the other pairs are unchanged. Combined outcome: " \
              "REF-DIVERGE if the supplement diverges, otherwise the frozen-history outcome.\n\n"
        md += "Agreement with the combined reference outcome:\n\n" + table(srs, lambda r: r["agreement"], KINDS)
        md += "\nOutcome on the supplementary histories alone (rerun pairs only):\n\n" + \
              table(ran, lambda r: r["reference_supplement"]["outcome"], KINDS)
        md += "\n| pair | Explorer | agreement (frozen histories) | agreement (combined) | supplementary histories |\n" \
              "|---|---|---|---|---|\n"
        m = 0
        for p in sorted(supp):
            s, c = supp[p], cur[p]
            if s["agreement"] != c["agreement"] or s.get("reference_supplement", {}).get("outcome", "REF-EQUIV-CHECKED") \
                    not in ("REF-EQUIV-CHECKED", "REF-DIVERGE"):
                m += 1
                rs_ = s["reference_supplement"]
                md += f"| {p} | {s['explorer'].get('verdict')} | {c['agreement']} | {s['agreement']} | " \
                      f"{rs_['outcome']} ({rs_['n_histories']}) |\n"
        md += f"\n{m} pairs listed (agreement changed, or the supplement was not fully supported).\n"
    final = RUNS / "e2_run.binding-final.jsonl"
    if final.exists() and supp:
        new = {r["pair_id"]: r for r in (json.loads(l) for l in final.read_text().splitlines() if l.strip())}
        nrs = list(new.values())
        for r in nrs:
            r["_col"] = r["kind"]
        md += "\n## Binding decision (BINDING_DECISION_2026-09-14.md, whisoo)\n\n"
        md += ("Selectors, tags, device IDs/categories, device counts and any/all do not decide the verdict (B1, B2); with "
               "several binding device sets for one service the pair is equal if some selector assignment is equal (B5). "
               "Both tools changed; pairs, histories, budget and start times are the frozen ones "
               "(`run_binding_v1.py`, `run_binding_b5.py`, `runs/e2_run.binding-final.jsonl`). Reference outcomes combine the "
               "frozen and supplementary histories as above.\n\n")
        md += "Explorer verdicts:\n\n" + table(nrs, lambda r: r["explorer"].get("verdict"), KINDS)
        md += "\nAgreement:\n\n" + table(nrs, lambda r: r["agreement"], KINDS)
        md += "\nReference outcome:\n\n" + table(nrs, lambda r: r["reference"]["outcome"], KINDS)
        faults = [r for r in nrs if r["kind"] == "fault"]
        fams = sorted({r["family"] for r in faults})
        for r in faults:
            r["_col"] = r["family"]
        md += "\nFault pairs, agreement by fault family:\n\n" + table(faults, lambda r: r["agreement"], fams)
        scope = sorted(p for p, r in new.items() if r["kind"] == "fault" and supp[p]["explorer"].get("verdict") == "DIVERGE"
                       and r["explorer"].get("verdict") == "EQUIV")
        md += ("\nFault pairs that are equal under the decision (reported as **out of scope: binding**, not as missed faults): "
               + ", ".join(f"`{p}` ({new[p]['family']})" for p in scope) + ".\n")
        md += "\n| pair | Explorer frozen → decision | reference frozen → decision | agreement frozen → decision | why |\n|---|---|---|---|---|\n"
        n = 0
        for p in sorted(new):
            o, r = supp[p], new[p]
            before = (o["explorer"].get("verdict"), o["reference"]["outcome"], o["agreement"])
            after = (r["explorer"].get("verdict"), r["reference"]["outcome"], r["agreement"])
            if before == after:
                continue
            n += 1
            sa = r["explorer"].get("selector_assignment") or r["reference"].get("selector_assignment") or {}
            why = ("B5 selector assignment" if sa.get("equiv_assignment") else
                   "B5: some assignments not decidable on the reference (history lacks a device only the JoI reads)"
                   if r["reference"].get("note", "").startswith("B5") else
                   "load: see explorer_note" if r.get("explorer_note") and before[0] != after[0] else "B1/B2 selector")
            md += f"| {p} | {before[0]} → {after[0]} | {before[1]} → {after[1]} | {before[2]} → {after[2]} | {why} |\n"
        md += f"\n{n} pairs differ from the frozen-history-plus-supplement results. "
        md += ("C05/fault2 and C05/fault3 were TIMEOUT in the combined run under CPU load and were rerun alone: REFUSED at the "
               "state cap, as in the frozen run (`explorer_under_load` keeps the loaded result).\n")
    (HERE / "RESULTS.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
