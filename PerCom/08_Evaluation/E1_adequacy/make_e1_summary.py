"""Build E1_SUMMARY.md: one view of the E1 depth cases (Stage A 12 + depth v2 8) and the breadth corpus counts.

~/temp/bin/python make_e1_summary.py      (run from E1_adequacy/)

Reads only recorded results; runs nothing:
- runs/e1_stageA.json                      Stage A 12 (after the 2026-09-12 audit)
- breadth/depth/runs/e1_depth_v2.json      depth 8 (v2, after the 2026-09-13 author adjudication)
- breadth/depth/RESULTS.md                 Explorer column of the depth 8 (auxiliary)
- breadth/corpus_100.csv                   author screening and R/B codes
"""
import csv
import json
import re
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
CODES = [f"R{i}" for i in range(1, 11)] + [f"B{i}" for i in range(1, 6)]


def frac_sum(values):
    a = b = 0
    for v in values:
        x, y = v.split("/")
        a, b = a + int(x), b + int(y)
    return a, b


def main():
    corpus = list(csv.DictReader(open(HERE / "breadth/corpus_100.csv", encoding="utf-8-sig", newline="")))
    seed_row = {r["prior_case_id"]: r for r in corpus if r["prior_case_id"]}
    row = {r["corpus_id"]: r for r in corpus}

    stage_a = json.loads((HERE / "runs/e1_stageA.json").read_text(encoding="utf-8"))
    depth = json.loads((HERE / "breadth/depth/runs/e1_depth_v2.json").read_text(encoding="utf-8"))
    explorer = {}
    for line in (HERE / "breadth/depth/RESULTS.md").read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) == 6 and re.fullmatch(r"E1-\d{3}", cells[0]):
            explorer[cells[0]] = cells[5]

    out = ["# E1 summary — depth 20 cases and breadth corpus", "",
           "Generated by `make_e1_summary.py` from recorded results; nothing is re-run. E1 adequacy = author semantic",
           "audit + reference execution. The Explorer column is auxiliary and is not part of any count.", "",
           "## Depth cases (20)", "",
           "| # | Case | Corpus ID | Cohort | Final label | Histories (tolerance / exact) | Explorer (aux) |",
           "|---:|---|---|---|---|---|---|"]
    match, exact = [], []
    for i, c in enumerate(stage_a, 1):
        r = seed_row[c["id"]]
        match.append(c["C_match"]); exact.append(c["C_exact"])
        ex = c["E_explorer"]
        out.append(f"| {i} | {c['id']} | {r['corpus_id']} | Stage A seed | complete | {c['C_match']} / {c['C_exact']} "
                   f"| {ex['verdict']} ({ex['claim']}) |")
    for i, c in enumerate(depth, len(stage_a) + 1):
        match.append(c["match"]); exact.append(c["exact"])
        out.append(f"| {i} | {c['id']} | {c['id']} | depth addition (v2) | {c['label']} | {c['match']} / {c['exact']} "
                   f"| {explorer.get(c['id'], '—')} |")
    m, n = frac_sum(match)
    e, _ = frac_sum(exact)
    labels = Counter("complete" if s.get("lang_claim") == "full" else s.get("lang_claim") for s in stage_a)
    labels.update(c["label"] for c in depth)
    out += ["", f"Histories: {m}/{n} within tolerance, {e}/{n} exact "
                f"(Stage A {frac_sum(x['C_exact'] for x in stage_a)[0]}/{frac_sum(x['C_exact'] for x in stage_a)[1]}, "
                f"depth v2 {frac_sum(x['exact'] for x in depth)[0]}/{frac_sum(x['exact'] for x in depth)[1]}).",
            "", "Final labels:"]
    out += [f"- {k}: {v}" for k, v in labels.most_common()]
    out += ["",
            "Stage A labels come from `results.md` (all 12 `full` after the audit). The boundary probes P1–P3 are",
            "outside these 20 (`results.md`, probe section). v1 depth results before the author adjudication are kept in",
            "`breadth/depth/RESULTS_v1_preaudit.md`.", ""]

    status = Counter(r["screen_status"] for r in corpus)
    by = Counter((r["source_stratum"], r["screen_status"]) for r in corpus)
    out += ["## Breadth corpus (100)", "",
            "Single-author manual screening and R/B coding; no second coder or kappa.", "",
            "| Source type | IN_SCOPE | AMBIGUOUS | OUT_OF_SCOPE | UNMATCHED | Total |", "|---|---:|---:|---:|---:|---:|"]
    for s in ("official", "research", "elicited", "community"):
        vals = [by[(s, k)] for k in ("IN_SCOPE", "AMBIGUOUS", "OUT_OF_SCOPE", "UNMATCHED")]
        out.append(f"| {s.capitalize()} | " + " | ".join(map(str, vals)) + f" | {sum(vals)} |")
    tot = [status[k] for k in ("IN_SCOPE", "AMBIGUOUS", "OUT_OF_SCOPE", "UNMATCHED")]
    out.append("| **Total** | " + " | ".join(f"**{v}**" for v in tot) + f" | **{sum(tot)}** |")
    dups = sum(1 for r in corpus if r["duplicate_family"])
    out += ["", f"Retained duplicates: {dups}.", ""]

    coded = [r for r in corpus if r["screen_status"] == "IN_SCOPE"]
    cnt = Counter(t.strip() for r in coded for t in r["rb_adjudicated"].split(","))
    out += [f"R/B codes (denominator {len(coded)} IN_SCOPE rows; a row can carry several codes):", "",
            "| " + " | ".join(CODES) + " |", "|" + "---:|" * len(CODES),
            "| " + " | ".join(str(cnt[c]) for c in CODES) + " |", "",
            f"Rows with at least one B code: {sum(1 for r in coded if 'B' in r['rb_adjudicated'])}.", ""]

    depth_ids = [seed_row[c["id"]]["corpus_id"] for c in stage_a] + [c["id"] for c in depth]
    assert all(row[i]["screen_status"] == "IN_SCOPE" for i in depth_ids)
    in_depth = Counter(t.strip() for i in depth_ids for t in row[i]["rb_adjudicated"].split(","))
    out += ["R/B codes within the 20 depth cases (author codes from the corpus file):", "",
            "| " + " | ".join(CODES) + " |", "|" + "---:|" * len(CODES),
            "| " + " | ".join(str(in_depth[c]) for c in CODES) + " |", ""]

    (HERE / "E1_SUMMARY.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
