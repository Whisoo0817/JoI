"""Aggregate all 92 E1 cases from recorded traces, including the E1-024 revision."""
import csv
import hashlib
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
spec = importlib.util.spec_from_file_location(
    "e1_trace_audit", HERE.parent / "extension72_plan/audit_outputs.py"
)
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)
inputs = {}


def read(relative):
    path = ROOT / relative
    inputs[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
    return json.loads(path.read_text())


def main():
    corpus_path = ROOT / "breadth/corpus_100.csv"
    inputs["breadth/corpus_100.csv"] = hashlib.sha256(corpus_path.read_bytes()).hexdigest()
    with corpus_path.open(encoding="utf-8-sig") as stream:
        corpus = list(csv.DictReader(stream))
    seed_ids = {r["prior_case_id"]: r["corpus_id"] for r in corpus if r["stage_a"] == "yes"}
    cases = {}

    def add(case_id, histories, origin):
        assert case_id not in cases, case_id
        assert histories, case_id
        cases[case_id] = {"histories": histories, "origin": origin}

    for row in read("runs/e1_stageA.json"):
        add(seed_ids[row["id"]], row["C_histories"], "original20")
    for row in read("breadth/depth/runs/e1_depth_v2.json"):
        add(row["id"], row["histories"], "original20")
    for batch in ("batch_er", "batch_official", "batch_community"):
        for row in read(f"breadth/remaining72/{batch}/runs/results.json"):
            add(row["id"], row["histories"], "extension72")

    revised = read("breadth/remaining72/e1_024_rolling/results.json")
    revised_histories = {h["name"]: h for h in revised["histories"]}
    original = cases["E1-024"]["histories"]
    for history in original:
        assert history["expected"] == revised_histories[history["name"]]["expected"]
    cases["E1-024"]["histories"] = [revised_histories[h["name"]] for h in original]
    supplemental = [h for h in revised["histories"] if h["name"] not in {x["name"] for x in original}]
    for relative in ("batch_community/runs/sensitivity_results.json", "batch_er/sensitivity/runs/results.json"):
        for row in read(f"breadth/remaining72/{relative}"):
            supplemental.extend(row["histories"])
    assert set(cases) == {r["corpus_id"] for r in corpus if r["screen_status"] == "IN_SCOPE"}

    def matched(histories):
        outcomes = [audit.trace_multiset_match(h["expected"], h["actual"]) for h in histories]
        assert outcomes == [h["exact"] for h in histories]
        return sum(outcomes)

    rows = []
    labels = {"official": "Official platform examples", "research": "Research examples",
              "elicited": "Published participant responses", "community": "Community requests"}
    for source, label in labels.items():
        collected = [r for r in corpus if r["source_stratum"] == source]
        evaluated = [r for r in collected if r["corpus_id"] in cases]
        histories = [h for r in evaluated for h in cases[r["corpus_id"]]["histories"]]
        rows.append(dict(source=source, label=label, collected=len(collected), evaluated=len(evaluated),
                         histories=len(histories), exact_histories=matched(histories)))
    total = {key: sum(r[key] for r in rows) for key in ("collected", "evaluated", "histories", "exact_histories")}
    result = dict(rows=rows, total=total,
                  all_histories_exact_cases=sum(matched(r["histories"]) == len(r["histories"]) for r in cases.values()),
                  supplemental=dict(histories=len(supplemental), exact_histories=matched(supplemental)),
                  revision="E1-024 replaces its original three histories with identical expectations; nine extra histories remain supplemental.",
                  comparison="Actions and exact timestamps; simultaneous actions form an unordered multiset; numeric tolerance 1e-9.",
                  provenance="Original 20 author-reviewed; additional 72 agent-derived interpretations. Finite tests of final encodings, not independent intent validation.",
                  case_counts={cid: dict(origin=r["origin"], histories=len(r["histories"]), exact_histories=matched(r["histories"])) for cid, r in sorted(cases.items())},
                  input_sha256=inputs)
    (HERE / "paper_summary.json").write_text(json.dumps(result, indent=2) + "\n")
    lines = ["# E1: all in-scope requests", "", "Generated by `make_paper_summary.py` from raw recorded traces.", "",
             "| Request source | Collected | Evaluated | Exact histories |", "| --- | ---: | ---: | ---: |"]
    for row in rows + [dict(label="Total", **total)]:
        lines.append(f"| {row['label']} | {row['collected']} | {row['evaluated']} | {row['exact_histories']}/{row['histories']} |")
    lines += ["", "All counts use final encodings under the recorded interpretations and assumptions. The E1-024 initial failure remains in its original result file.", "",
              f"Additional diagnostics: {result['supplemental']['exact_histories']}/{len(supplemental)} histories, excluded from the table. Legacy P1–P3 probes and the JoI fallback are also excluded."]
    (HERE / "PAPER_TABLE.md").write_text("\n".join(lines) + "\n")
    print(json.dumps({key: result[key] for key in ("rows", "total", "all_histories_exact_cases", "supplemental")}, indent=2))


if __name__ == "__main__":
    main()
